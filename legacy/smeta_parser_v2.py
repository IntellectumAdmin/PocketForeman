class SmetaParser:

    def __init__(self, pdf_path: str):
        self.pdf_path = pdf_path
        self.work_items = []
        self.skipped = {
            'material': 0,
            'equipment': 0,
            'internal': 0,
            'no_volume': 0,
            'parse_error': 0,
        }
        self.parse_errors = []

    def run(self) -> dict:
        pdf_path = Path(self.pdf_path)
        if not pdf_path.exists():
            raise FileNotFoundError(f"Файл не найден: {self.pdf_path}")

        print("=" * 65)
        print("STRUCTURAL SMETA PARSER v3.0 — AINTELLECTUM")
        print("Архитектура: Аян | Разработка: Claude | Капитан: Ереке")
        print("=" * 65)
        print(f"\nФайл: {pdf_path.name}")

        with pdfplumber.open(self.pdf_path) as pdf:
            total_pages = len(pdf.pages)
            print(f"Страниц в PDF: {total_pages}")
            print(f"\nОбработка...", end='', flush=True)
            for page_num, page in enumerate(pdf.pages, 1):
                if page_num % 100 == 0:
                    print(f" {page_num}", end='', flush=True)
                self._process_page(page, page_num)
            print(f" {total_pages} готово!")

        return self._build_result()

    def _process_page(self, page, page_num: int):
        try:
            tables = page.extract_tables()
            if not tables:
                return
            for table in tables:
                self._process_table(table, page_num)
        except Exception as e:
            self.skipped['parse_error'] += 1
            self.parse_errors.append({'page': page_num, 'error': str(e)})

    def _process_table(self, table: list, page_num: int):
        if not table:
            return
        code_col = find_code_column(table)

        for row in table:
            if not row:
                continue

            def c(offset=0) -> str:
                if code_col is None:
                    return ''
                idx = code_col + offset
                return str(row[idx] or '').strip() if idx < len(row) else ''

            if code_col is not None:
                raw_code = c(0)
                name     = c(1)
                unit_raw = c(2)
                qty_raw  = c(3)
            else:
                raw_code, name, unit_raw, qty_raw = self._scan_row(row)

            code = extract_code(raw_code)

            if not code:
                self.skipped['internal'] += 1
                continue
            if RE_MATERIAL.match(code):
                self.skipped['material'] += 1
                continue
            if RE_EQUIP.match(code):
                self.skipped['equipment'] += 1
                continue
            if not RE_WORK.match(code):
                self.skipped['internal'] += 1
                continue

            # Классифицируем работу по коду
            classification = classify_work(code)

            unit_norm, coeff = normalize_unit(unit_raw)
            volume = parse_volume(qty_raw)

            if volume is None:
                self.skipped['no_volume'] += 1
            elif coeff != 1.0:
                volume *= coeff

            self.work_items.append({
                'name': name,
                'code': code,
                'unit': unit_norm,
                'volume': volume or 0.0,
                'has_volume': volume is not None,
                'phase': classification['phase'],
                'phase_order': classification['phase_order'],
                'subgroup': classification['subgroup'],
                'page': page_num,
            })

    def _scan_row(self, row: list) -> tuple:
        for i, cell in enumerate(row):
            code = extract_code(str(cell or ''))
            if RE_WORK.match(code) or RE_MATERIAL.match(code) or RE_EQUIP.match(code):
                g = lambda o: str(row[i+o] or '').strip() if i+o < len(row) else ''
                return str(cell or '').strip(), g(1), g(2), g(3)
        return '', '', '', ''

    def _build_result(self) -> dict:
        # Статистика по фазам
        phases = {}
        for w in self.work_items:
            p = w['phase']
            if p not in phases:
                phases[p] = {'count': 0, 'order': w['phase_order']}
            phases[p]['count'] += 1

        phases_sorted = dict(sorted(phases.items(), key=lambda x: x[1]['order']))

        return {
            'meta': {
                'parser_version': '3.0',
                'source': str(self.pdf_path),
                'total_work_items': len(self.work_items),
                'skipped': self.skipped,
                'phases_count': len(phases),
            },
            'work_items': self.work_items,
            'phases_summary': {k: v['count'] for k, v in phases_sorted.items()},
            'parse_errors': self.parse_errors,
        }

    def print_summary(self, result: dict):
        meta = result['meta']
        print("\n" + "=" * 65)
        print("РЕЗУЛЬТАТ ПАРСИНГА v3.0")
        print("=" * 65)
        print(f"\n  Работ извлечено:             {meta['total_work_items']:>6}")
        print(f"  Пропущено материалов (2xxx): {self.skipped['material']:>6}")
        print(f"  Пропущено оборудования:      {self.skipped['equipment']:>6}")
        print(f"  Пропущено состав/итоги:      {self.skipped['internal']:>6}")
        print(f"  Без объёма:                  {self.skipped['no_volume']:>6}")
        print(f"\n  Фаз ГПР: {meta['phases_count']}")

        print(f"\nФАЗЫ ГПР (по порядку строительства):")
        for phase, cnt in result['phases_summary'].items():
            print(f"  {cnt:>5} работ | {phase}")

        cable = [w for w in result['work_items'] if 'кабел' in w['name'].lower()]
        if cable:
            total = sum(w['volume'] for w in cable)
            print(f"\nКАБЕЛЬ: {len(cable)} позиций | {total:,.0f} м")


