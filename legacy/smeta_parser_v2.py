# ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# ═══════════════════════════════════════════════════════════════

def parse_volume(value) -> float | None:
    if value is None:
        return None
    s = str(value).strip()
    if not s or s in ('-', '—', '–', 'x', 'х', 'X'):
        return None
    s = re.sub(r'(\d)\s+(\d)', r'\1\2', s)
    s = s.replace(',', '.')
    s = re.sub(r'[^\d.]', '', s)
    if not s:
        return None
    try:
        val = float(s)
        return val if val > 0 else None
    except ValueError:
        return None


UNIT_MAP = {
    'м2': 'м2', 'м²': 'м2', 'кв.м': 'м2', 'кв.м.': 'м2', 'm2': 'м2',
    'м3': 'м3', 'м³': 'м3', 'куб.м': 'м3', 'куб.м.': 'м3', 'm3': 'м3',
    'м': 'м', 'п.м': 'м', 'пог.м': 'м', 'п.м.': 'м',
    'т': 'т', 'тн': 'т', 'тонн': 'т',
    'кг': 'кг',
    'шт': 'шт', 'шт.': 'шт', 'штук': 'шт',
    'компл': 'компл', 'компл.': 'компл', 'комплект': 'компл',
    'набор': 'набор',
    'чел-час': 'чел-час', 'чел.час': 'чел-час', 'чел.-ч': 'чел-час',
    'маш-ч': 'маш-ч',
}

def normalize_unit(unit: str) -> tuple:
    u = (unit or '').strip().lower()
    if u in ('км', 'km'):
        return 'м', 1000.0
    u_first = u.split()[0] if u else u
    return UNIT_MAP.get(u_first, UNIT_MAP.get(u, u)), 1.0


def find_code_column(table: list) -> int | None:
    for row in table[:30]:
        if not row:
            continue
        for j, cell in enumerate(row):
            code = extract_code(str(cell or ''))
            if RE_WORK.match(code) or RE_MATERIAL.match(code):
                return j
    return None


