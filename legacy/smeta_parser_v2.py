RE_WORK     = re.compile(r'^6\d{3}-\d{4}-\d{4}')
RE_MATERIAL = re.compile(r'^2\d{2}-\d{3}-\d{4}')
RE_EQUIP    = re.compile(r'^3\d{2}-')

def extract_code(cell: str) -> str:
    m = re.match(r'^(\d{4}-\d{4}-\d{4}|\d{3}-\d{3}-\d{4})', (cell or '').strip())
    return m.group(1) if m else ''


