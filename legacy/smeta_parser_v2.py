    info = WORK_CLASSIFIER.get(p4, {})
    phase = info.get('phase', f'Прочие ({p4})')
    order = info.get('phase_order', 99)
    subgroup = info.get('sub', {}).get(p9, '')

    return {'phase': phase, 'phase_order': order, 'subgroup': subgroup}


